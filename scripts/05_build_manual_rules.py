"""Build ``manual_fix_rules.jsonl`` from the hand-written TSVs in ``inputs/``.

``conflict_resolutions.tsv``: the author's decisions for variants the learned files
disagreed on, ``variant<TAB>context<TAB>replacement`` (see ``resolution_rule``; 09 removes
these variants from the learned files). ``manual_fixes.tsv``: fixes asked for directly,
``variant<TAB>replacement``. ``convention_fixes.tsv``: generated by
``06_build_convention_fixes.py`` (the label spelling conventions as output fixes), same
two columns. ``#`` starts a comment.

The patterns come from 02's ``variant_pattern`` and are merged per replacement exactly as
03_merge_rules.py does, so the file has the same format as the learned rules. TSVs are
read in that order and a variant whose pattern an earlier line already holds is skipped,
so a decision beats a manual fix, which beats a convention.

Consumers apply this file LAST, after the drug and term rules, so the conventions also
respell what a learned rule wrote. It used to go first so that a hand fix would win
(``lodose`` -> ``lowdose`` over the learned ``Lodoz``); the variants the files fought over
are now taken out of the learned files instead (``09_apply_resolutions.py``), so order no
longer decides them.

It also refreshes the lookup-table form (``lookup/manual_fix_rules.lookup.json`` by
default, see ``08_build_lookup.py``), since a hand edit of a TSV is the one change made
outside a full build and the lookup must follow it. ``--no-lookup`` skips that.

Usage: uv run scripts/05_build_manual_rules.py [TSV ...] [--out OUT.jsonl] [--lookup-out OUT.lookup.json]
This file was written by Claude Code.
"""
import importlib.util
import json
from pathlib import Path

import click
from loguru import logger

_HERE = Path(__file__).resolve().parent
_spec = importlib.util.spec_from_file_location("b", _HERE / "02_build_fix_rules.py")
b = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(b)
_mspec = importlib.util.spec_from_file_location("m", _HERE / "03_merge_rules.py")
m = importlib.util.module_from_spec(_mspec)
_mspec.loader.exec_module(m)
# 08 owns the lookup format; loaded here only to refresh the manual lookup after a rebuild.
_lspec = importlib.util.spec_from_file_location("lk", _HERE / "08_build_lookup.py")
lk = importlib.util.module_from_spec(_lspec)
_lspec.loader.exec_module(lk)


INPUTS = _HERE.parent / "inputs"
RESOLUTIONS = INPUTS / "conflict_resolutions.tsv"
DEFAULT_TSVS = (RESOLUTIONS, INPUTS / "manual_fixes.tsv", INPUTS / "convention_fixes.tsv")


def read_rows(lines) -> list[list[str]]:
    """The tab-separated fields of each line that is not blank or a comment (a trailing
    empty field, the empty replacement of a resolution, is kept)."""
    return [line.rstrip("\r\n").split("\t") for line in lines if line.strip() and not line.lstrip().startswith("#")]


def resolution_rule(variant: str, context: str, replacement: str) -> tuple[str, dict | None]:
    """``(pattern, rule)`` for one ``conflict_resolutions.tsv`` line; ``rule`` is None for an
    empty replacement (no rule, but the pattern stays taken so no later line fixes it).

    ``*`` is a plain rule. ``after:WORDS`` puts the context words in the variant and the
    replacement (``after:de`` with a replacement starting with ``d'`` consumes the ``de``).
    ``before:WORDS`` is its mirror: the words follow the variant and the replacement.
    ``before_vowel`` gives a rule that ends on the whitespace before a word starting with a
    vowel or h, which the replacement eats (02's ``before_vowel_pattern``).

    >>> [resolution_rule(*row)[1]["variant"] for row in [("lodose", "after:scanner", "low-dose"),
    ...  ("areus", "after:l'", "Aerius"), ("démolyse", "after:de", "d'hémolyse")]]
    ['scanner lodose', "l'areus", 'de démolyse']
    >>> resolution_rule("areus", "after:l'", "Aerius")[1]["replacement"], resolution_rule("matro", "*", "")[1]
    ("l'Aerius", None)
    >>> r = resolution_rule("antibial", "before:postérieure", "en tibiale")[1]
    >>> r["variant"], r["replacement"]
    ('antibial postérieure', 'en tibiale postérieure')
    """
    rule = {"variant": variant, "replacement": replacement}
    if context.startswith("after:"):
        words = context[len("after:"):]
        if not (words == "de" and replacement.startswith("d'")):
            sep = "" if words.endswith("'") else " "
            rule["replacement"] = words + sep + replacement
        rule["variant"] = words + ("" if words.endswith("'") else " ") + variant
    elif context.startswith("before:"):
        words = context[len("before:"):]
        rule["variant"], rule["replacement"] = f"{variant} {words}", f"{replacement} {words}"
    elif context == "before_vowel":
        rule["before_vowel"] = True
    else:
        assert context == "*", f"unknown context {context!r} for {variant!r}"
    pattern = (b.before_vowel_pattern if context == "before_vowel" else b.variant_pattern)(rule["variant"])
    return pattern, (dict(rule, pattern=pattern) if replacement else None)


def build_manual_rules(lines) -> list[dict]:
    """Merged rules from ``variant<TAB>replacement`` and ``variant<TAB>context<TAB>replacement`` lines.

    >>> rules = build_manual_rules(["# c", "lodose\\tlowdose", "lodoses\\tlowdose", "ceresta\\tSeresta", "céresta\\tcérestat"])
    >>> [(r.get("variants") or [r["variant"]], r["replacement"]) for r in rules]
    [(['lodose', 'lodoses'], 'lowdose'), (['ceresta'], 'Seresta')]
    >>> fix = b.compile_rules(rules)
    >>> fix("deux Lodoses et du céresta, la dose")  # a capital initial is kept
    'deux Lowdose et du Seresta, la dose'

    A resolution line takes its pattern first, an empty one included:

    >>> [r["replacement"] for r in build_manual_rules(["matro\\t*\\t", "matro\\tmétro", "lodose\\t*\\tLodoz", "lodose\\tlowdose"])]
    ['Lodoz']
    """
    rules, seen = [], set()
    for row in read_rows(lines):
        if len(row) == 3:
            pattern, rule = resolution_rule(*row)
        else:
            variant, replacement = row
            pattern = b.variant_pattern(variant)
            rule = {"variant": variant, "pattern": pattern, "replacement": replacement}
        if pattern not in seen:
            seen.add(pattern)
            if rule:
                rules.append(rule)
    return [r for _, r in m.merge_rules(rules)]


@click.command()
@click.argument("tsvs", nargs=-1, type=click.Path(exists=True, path_type=Path))
@click.option("--out", type=click.Path(path_type=Path), default=_HERE.parent / "rules" / "manual_fix_rules.jsonl", show_default=True)
@click.option("--lookup-out", type=click.Path(path_type=Path), default=None,
              help="lookup file to refresh; default lookup/<OUT stem>.lookup.json for the default OUT, "
                   "else OUT with a .lookup.json suffix")
@click.option("--no-lookup", is_flag=True, help="do not write the lookup form")
def main(tsvs: tuple[Path, ...], out: Path, lookup_out: Path | None, no_lookup: bool) -> None:
    tsvs = tsvs or DEFAULT_TSVS
    rules = build_manual_rules([line for tsv in tsvs for line in tsv.read_text(encoding="utf-8").splitlines()])
    with out.open("w", encoding="utf-8") as f:
        f.writelines(json.dumps(r, ensure_ascii=False) + "\n" for r in rules)
    logger.info(f"{', '.join(t.name for t in tsvs)} -> {out}: {len(rules)} rules")
    if not no_lookup:
        # A custom OUT gets its lookup beside it, so a trial build never overwrites lookup/.
        if lookup_out is None and out.resolve() != (_HERE.parent / "rules" / "manual_fix_rules.jsonl").resolve():
            lookup_out = out.with_suffix(".lookup.json")
        lk.build_lookup_file(out, lookup_out)


if __name__ == "__main__":
    main()
